const targets = [
  { path: resolve(root, 'src/styles/tokens.generated.css'), content: generateCss(bank) },
  { path: resolve(root, 'src/design/tokens.generated.ts'), content: generateTs(bank) },
  { path: resolve(root, 'tailwind.preset.generated.js'), content: generateTailwindPresetEsm(bank) },
  { path: resolve(root, 'tailwind.preset.generated.cjs'), content: generateTailwindPresetCjs(bank) },
  { path: resolve(root, 'ios/App/App/DesignTokens.generated.swift'), content: generateSwift(bank) },
  { path: resolve(root, 'android/app/src/main/res/values/design_tokens.generated.xml'), content: generateAndroidXml(bank) },
  { path: resolve(root, 'android/app/src/main/java/com/lekitduvoyageur/app/LKDVTheme.generated.kt'), content: generateKotlin(bank) },
];

for (const target of targets) {
  if (/\bundefined\b/.test(target.content)) {
    console.error(`❌ Undefined token detected in target: ${target.path}`);
    process.exit(1);
  }
}

let hasMismatch = false;

for (const target of targets) {
  const dir = dirname(target.path);
  if (!existsSync(dir)) {
    if (isCheck) {
      console.error(`[check] Directory does not exist: ${dir}`);
      hasMismatch = true;
      continue;
    }
    mkdirSync(dir, { recursive: true });
  }

  if (isCheck) {
    if (!existsSync(target.path)) {
      console.error(`[check] Missing file: ${target.path}`);
      hasMismatch = true;
    } else {
      const existing = readFileSync(target.path, 'utf8');
      if (existing !== target.content) {
        console.error(`[check] Content mismatch in: ${target.path}`);
        hasMismatch = true;
      }
    }
  } else {
    writeFileSync(target.path, target.content, 'utf8');
    console.log(`[generated] ${target.path.replace(root + '/', '')}`);
  }
}

if (isCheck) {
  if (hasMismatch) {
    console.error('❌ Design bank artifacts are out of sync. Run "npm run design:generate".');
    process.exit(1);
  } else {
    console.log('✅ All design bank generated artifacts are in sync with src/design/bank.ts.');
    process.exit(0);
  }
} else {
  console.log('✅ All 7 design bank artifacts generated successfully from src/design/bank.ts.');
}
