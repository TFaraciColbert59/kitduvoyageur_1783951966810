#!/usr/bin/env node
/**
 * BUILD HEROICONS IMPORT MAP
 * =========================
 * Génère `src/components/ui/Icon/heroicons.generated.ts` : les NOMS Heroicons
 * réellement résolus par le primitif `Icon`, en imports nommés.
 *
 * Pourquoi : l'import namespace `import * as HeroIcons` utilisé comme table de
 * correspondance à l'exécution empêche tout élagage — les 648 modules du jeu
 * complet partaient dans le bundle (71,7 Ko gzip) pour 21 icônes utilisées.
 *
 * Signale les noms d'icônes que ni le pack local (PNG/SF) ni cette table ne
 * résolvent : ils afficheraient le placeholder ✦.
 *
 * Usage : node scripts/icons/build-heroicons-map.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const OUT = path.join(root, 'src/components/ui/Icon/heroicons.generated.ts');

/* ---------- 1. Noms d'icônes réellement passés au primitif `Icon` ---------- */
const walk = (dir, out = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.next', '.git'].includes(entry.name)) continue;
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(entry.name)) out.push(p);
  }
  return out;
};

const used = new Set();
for (const file of walk(path.join(root, 'src'))) {
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    // Commentaires : un nom cité en prose n'est pas un glyphe demandé.
    if (/^\s*(\/\/|\*|\/\*)/.test(line)) continue;
    // `FooIcon.displayName = 'FooIcon'` déclare un composant LOCAL
    // (src/components/icons/*.tsx) qui n'est jamais passé au primitif.
    if (/displayName\s*=/.test(line)) continue;
    if (/^\s*import\s/.test(line)) continue;
    for (const m of line.matchAll(/['"`]([A-Z][A-Za-z0-9]*Icon(?:Solid)?)['"`]/g)) {
      // 'SolidIcon' / 'IconSolid' sont des MARQUEURS DE SUFFIXE internes à
      // resolveHeroComponent, pas des noms de glyphe.
      if (m[1] === 'SolidIcon' || m[1] === 'IconSolid') continue;
      used.add(m[1]);
    }
  }
}

/* ---------- 2. Ce que les packs locaux savent déjà résoudre ---------- */
const registry = fs.readFileSync(path.join(root, 'src/components/ui/Icon/registry.ts'), 'utf8');
// Scope au SEUL objet PNG_ICON_MAP. Le regex precedant balayait tout objet a
// 2 espaces du fichier, donc aussi LEGACY_GLYPH_ALIASES (noms SF, pas des
// PNG) : packHit() repondait alors "true" via le faux pack PNG et le
// generateur pouvait ignorer silencieusement un glyphe manquant au lieu
// d'echouer bruyamment.
const pngMapBlock = registry.match(/PNG_ICON_MAP[^=]*=\s*\{[\s\S]*?\n\};/);
if (!pngMapBlock) {
  console.error('\u2717 PNG_ICON_MAP introuvable dans registry.ts');
  process.exit(1);
}
const pngPack = new Set([...pngMapBlock[0].matchAll(/^\s{2}([A-Za-z0-9_]+):\s*'/gm)].map((m) => m[1]));

const aliasBlock = registry.match(/LEGACY_GLYPH_ALIASES[\s\S]*?\n};/);
const aliases = aliasBlock
  ? new Set([...aliasBlock[0].matchAll(/([A-Za-z0-9]+):\s*'([^']+)'/g)].map((m) => m[1]))
  : new Set();

const manifest = fs.readFileSync(path.join(root, 'src/components/ui/Icon/registry.generated.ts'), 'utf8');
const sfPack = new Set([...manifest.matchAll(/^\s{2}'([^']+)',/gm)].map((m) => m[1]));

const packHit = (name) => {
  let key = name;
  if (!/Icon$|IconSolid$|SolidIcon$/.test(key)) key = `${name}Icon`;
  return pngPack.has(key) || pngPack.has(name) || sfPack.has(name) || sfPack.has(`${name}-fill`) || aliases.has(name);
};

/* ---------- 3. Ce que Heroicons sait fournir ---------- */
const heroDir = path.join(root, 'node_modules/@heroicons/react/24');
if (!fs.existsSync(heroDir)) {
  console.error('✗ @heroicons/react introuvable — lancez `npm install`.');
  process.exit(1);
}
const available = (variant) =>
  new Set(
    fs
      .readdirSync(path.join(heroDir, variant))
      .filter((f) => f.endsWith('.js') && f !== 'index.js')
      .map((f) => f.slice(0, -3)),
  );
const outline = available('outline');
const solid = available('solid');

/** `FooSolidIcon` / `FooIconSolid` → `FooIcon` (convention de `resolveHeroComponent`). */
const baseName = (n) =>
  n.endsWith('SolidIcon') ? `${n.slice(0, -'SolidIcon'.length)}Icon`
  : n.endsWith('IconSolid') ? `${n.slice(0, -'IconSolid'.length)}Icon`
  : n;

const inOutline = new Set();
const inSolid = new Set();
for (const name of used) {
  if (packHit(name)) continue;
  const base = baseName(name);
  if (outline.has(base)) inOutline.add(base);
  if (solid.has(base)) inSolid.add(base);
}

const unresolved = [...used].filter(
  (n) => !packHit(n) && !outline.has(baseName(n)) && !solid.has(baseName(n)),
);

/* ---------- 4. Émission ---------- */
const lines = [
  '// AUTO-GENERATED by scripts/icons/build-heroicons-map.mjs — do not edit by hand.',
  '//',
  "// Imports nommés des seules icônes Heroicons que l'app résout réellement.",
  "// Remplace l'ancien `import * as HeroIcons from '@heroicons/react/24/outline'`",
  '// (648 modules, non élagables car utilisés comme table de correspondance à',
  "// l'exécution) : le reste du jeu disparaît du bundle.",
  '/* eslint-disable */',
  "import type React from 'react';",
  '',
];

// Les deux variantes exposent les MEMES noms : on aliasle l'import solid
// (`StarIcon as StarIconSolid`) pour éviter toute collision de portée.
const emit = (set, variant) => {
  const names = [...set].sort();
  if (names.length === 0) return;
  const local = (n) => (variant === 'solid' ? `${n}Solid` : n);
  lines.push('import {');
  for (const n of names) lines.push(`  ${n}${n === local(n) ? '' : ` as ${local(n)}`},`);
  lines.push(`} from '@heroicons/react/24/${variant}';`);
  lines.push('');
};
emit(inOutline, 'outline');
emit(inSolid, 'solid');

const type = 'Record<string, React.ComponentType<React.SVGProps<SVGSVGElement>>>';
lines.push('/** Icônes Heroicons résolvables, par variante. Table statique : fully élaguable. */');
lines.push(`export const HERO_OUTLINE: ${type} = {`);
for (const n of [...inOutline].sort()) lines.push(`  ${n},`);
lines.push('};');
lines.push('');
lines.push(`export const HERO_SOLID: ${type} = {`);
for (const n of [...inSolid].sort()) lines.push(`  ${n}: ${n}Solid,`);
lines.push('};');
lines.push('');

fs.writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(
  `✓ ${inOutline.size} icônes outline + ${inSolid.size} solid importées nommément — ${path.relative(root, OUT)}`,
);
console.log(`  (au lieu de ${outline.size} + ${solid.size} modules du jeu complet)`);
if (unresolved.length > 0) {
  console.warn(
    `⚠ ${unresolved.length} nom(s) sans glyphe — placeholder ✦ : ${unresolved.join(', ')}`,
  );
}
