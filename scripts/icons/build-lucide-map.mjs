#!/usr/bin/env node
/**
 * BUILD LUCIDE IMPORT MAP
 * =======================
 * Génère `src/components/ui/Icon/lucide.generated.ts` : les seuls icônes
 * Lucide réellement résolues par le primitif `Icon` (`Icon.tsx`), en imports
 * nommés afin que webpack/Next puisse élaguer les ~1 500+ autres icônes
 * (gain ~190 Ko gzip dans le layout racine).
 *
 * Usage : node scripts/icons/build-lucide-map.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const lucide = require('lucide-react');

const root = process.cwd();
const OUT = path.join(root, 'src/components/ui/Icon/lucide.generated.ts');

const isLucideComponent = (val) =>
  typeof val === 'function' ||
  (typeof val === 'object' && val !== null && '$$typeof' in val);

// Map every Lucide export to its canonical (shortest non-Icon-suffixed) export name
// so we never import duplicate aliases (e.g. Home + HomeIcon).
const lucideKeys = new Set(
  Object.keys(lucide).filter((k) => /^[A-Z]/.test(k) && isLucideComponent(lucide[k])),
);

const canonicalFor = (key) => {
  if (!lucideKeys.has(key)) return null;
  if (key.endsWith('Icon')) {
    const stripped = key.slice(0, -4);
    if (lucideKeys.has(stripped) && lucide[stripped] === lucide[key]) {
      return stripped;
    }
  }
  return key;
};

const resolveToCanonical = (raw) => {
  if (!raw || typeof raw !== 'string' || raw.length > 48) return null;
  const direct = canonicalFor(raw);
  if (direct) return direct;

  let clean = raw;
  if (clean.endsWith('SolidIcon')) clean = clean.slice(0, -9);
  else if (clean.endsWith('IconSolid')) clean = clean.slice(0, -9);
  else if (clean.endsWith('Icon')) clean = clean.slice(0, -4);

  const cleanCanon = canonicalFor(clean);
  if (cleanCanon) return cleanCanon;

  const pascal = clean
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('');

  return canonicalFor(pascal);
};

const needed = new Set();

// 1. All targets declared in SEMANTIC_LUCIDE_MAP inside Icon.tsx
const iconSrc = fs.readFileSync(path.join(root, 'src/components/ui/Icon/Icon.tsx'), 'utf8');
const semBlock = iconSrc.match(/SEMANTIC_LUCIDE_MAP[\s\S]*?\n\};/);
if (!semBlock) {
  console.error('✗ SEMANTIC_LUCIDE_MAP introuvable dans Icon.tsx');
  process.exit(1);
}
for (const m of semBlock[0].matchAll(/:\s*'([A-Za-z0-9]+)'/g)) {
  const c = resolveToCanonical(m[1]);
  if (c) needed.add(c);
}

// 2. Walk src/ to collect every icon name passed to Icon / AppIcon / LkvIcon or icon props
const walk = (dir, out = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.next', '.git'].includes(entry.name)) continue;
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(entry.name)) out.push(p);
  }
  return out;
};

for (const file of walk(path.join(root, 'src'))) {
  if (
    file.endsWith('lucide.generated.ts') ||
    file.endsWith('heroicons.generated.ts') ||
    file.endsWith('registry.generated.ts') ||
    file.endsWith('instagram.generated.ts')
  ) {
    continue;
  }
  const txt = fs.readFileSync(file, 'utf8');
  if (!/(Icon|icon)/.test(txt)) continue;

  for (const m of txt.matchAll(
    /<(?:Icon|AppIcon|LkvIcon)\b[^>]*?\bname\s*=\s*(?:"([^"]+)"|'([^']+)')/g,
  )) {
    const c = resolveToCanonical(m[1] || m[2]);
    if (c) needed.add(c);
  }
  for (const m of txt.matchAll(
    /\b(?:icon|iconName|tabIcon|leftIcon|rightIcon|glyph)\s*[:=]\s*(?:"([^"]+)"|'([^']+)')/g,
  )) {
    const c = resolveToCanonical(m[1] || m[2]);
    if (c) needed.add(c);
  }
  if (/components\/ui\/(?:Icon|AppIcon|LkvIcon)/.test(txt)) {
    for (const m of txt.matchAll(/['"]([A-Za-z][A-Za-z0-9_-]{1,38})['"]/g)) {
      const val = m[1];
      if (/Icon(?:Solid)?$|SolidIcon$/.test(val) || /^[a-z]+-[a-z0-9-]+$/.test(val)) {
        const c = resolveToCanonical(val);
        if (c) needed.add(c);
      }
    }
  }
}

const sorted = [...needed].sort();
const lines = [
  '// AUTO-GENERATED by scripts/icons/build-lucide-map.mjs — do not edit by hand.',
  '//',
  "// Imports nommés des seules icônes Lucide que le primitif Icon résout réellement.",
  "// Évite `import * as LucideIcons from 'lucide-react'` (~204 Ko gzip dans le layout racine).",
  '',
  "import type React from 'react';",
  'import {',
  ...sorted.map((name) => `  ${name},`),
  "} from 'lucide-react';",
  '',
  'export const LUCIDE_ICONS: Record<string, React.ComponentType<any>> = {',
  ...sorted.map((name) => `  ${name},`),
  '};',
  '',
];

const nextContent = lines.join('\n');
const prevContent = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
if (prevContent !== nextContent) {
  fs.writeFileSync(OUT, nextContent, 'utf8');
  console.log(`✓ lucide.generated.ts mis à jour (${sorted.length} icônes)`);
} else {
  console.log(`✓ lucide.generated.ts à jour (${sorted.length} icônes)`);
}
