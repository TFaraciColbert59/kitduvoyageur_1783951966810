export function resolveLKDVFile(name: string): string | undefined {
  const token = name.replace(/(IconSolid|SolidIcon|Icon)$/,'').replace(/([a-z0-9])([A-Z])/g,'$1-$2').replace(/([A-Z])([A-Z][a-z])/g,'$1-$2').replace(/[_ ]/g,'-').toLowerCase();
  const direct=token.replace(/-/g,'_');
  if(LKDV_ASSET_NAMES.has(direct))return direct;
  const alias=ALIASES[token];
  return alias&&LKDV_ASSET_NAMES.has(alias)?alias:undefined;
}
