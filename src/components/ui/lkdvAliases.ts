const KEYS: ReadonlySet<string> = new Set(LKDV_ICON_NAMES);

/** `HeartIconSolid` / `MapPinIcon` / `check_circle` → `heart` / `map-pin` / `check-circle`. */
export function normalizeIconName(name: string): string {
  return name
    .replace(/(IconSolid|SolidIcon|Icon)$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/_/g, '-')
    .toLowerCase();
}

export function isLKDVIconName(name: string): name is LKDVIconName {
  return KEYS.has(name);
}

/**
 * Résout n'importe quel nom (clé LKDV, nom lucide/Heroicons/kebab hérité) vers une clé LKDV V2.
 * Renvoie `undefined` si le nom n'a pas d'équivalent dans la base : il ne faut alors ni inventer
 * ni retomber sur une autre bibliothèque.
 */
export function resolveLKDVIcon(name: string): LKDVIconName | undefined {
  if (isLKDVIconName(name)) return name;
  const token = normalizeIconName(name);
  const direct = token.replace(/-/g, '_');
  if (isLKDVIconName(direct)) return direct;
  return LKDV_ALIASES[token];
}
