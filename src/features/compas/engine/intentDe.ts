const TENS: Record<string, number> = { zwanzig: 20, dreißig: 30, dreissig: 30, vierzig: 40, funfzig: 50 };
const NUMBERS: Record<string, number> = { ...UNITS, ...TEENS, ...TENS };
for (const [t, tv] of Object.entries(TENS))
  for (const [u, uv] of Object.entries(UNITS)) NUMBERS[`${u === 'eins' ? 'ein' : u}und${t}`] = tv + uv;

/** Nombre dit en lettres ou en chiffres (texte replié). */
const numberOf = (s: string | undefined): number | null => {
  const k = fold(s ?? '');
  if (/^\d+$/.test(k)) return Number(k);
  return NUMBERS[k] ?? null;
};
const NUM_WORD = `\\d+|${Object.keys(NUMBERS).sort((a, b) => b.length - a.length).join('|')}`;

